-- Правило: в одни календарные сутки можно проснуться только один раз.
-- У активностей типа id=1 «Ночной сон» дата окончания уникальна.
--
-- На этом держится расчёт границ дня:
--   fact_start(D) = начало сна, закончившегося в D;
--   fact_end(D)   = начало сна, закончившегося в D+1.
-- Раньше при двух снах с одной датой окончания брался самый ранний,
-- второй молча игнорировался. Теперь вторая запись запрещена в БД.
--
-- Уникальность по дате ОКОНЧАНИЯ, не начала: сон 14.11 03:00→10:00 и
-- сон 14.11 22:00→15.11 06:00 начинаются в один день, но заканчиваются
-- в разные — корректная пара, конфликта нет.
--
-- Незавершённые сны (end_time NULL или '') в индекс не попадают:
-- их можно создавать, ограничение сработает при заполнении конца.
-- Индекс действует на INSERT и UPDATE, включая импорт и правки через UI.

CREATE UNIQUE INDEX IF NOT EXISTS idx_activities_one_night_sleep_per_day
ON activities(substr(end_time, 1, 10))
WHERE activity_type_id = 1
  AND end_time IS NOT NULL
  AND end_time <> '';